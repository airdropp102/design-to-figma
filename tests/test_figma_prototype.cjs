const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('scripts/figma_prototype_handler.js', 'utf8');
const page = {id:'0:1', type:'PAGE'};
let writes = 0;
const root = {id:'1:1',type:'FRAME',parent:page,overflowDirection:'NONE',clipsContent:false};
root.resize=(w,h)=>{root.width=w;root.height=h;};root.width=1440;root.height=4432;
const dest = {id:'2:1',type:'FRAME',parent:page};
const button = {id:'1:2',type:'FRAME',parent:root,reactions:[],async setReactionsAsync(r){writes++;this.reactions=r;}};
const foreign = {id:'9:1',type:'FRAME',parent:{id:'9:0',type:'PAGE'}};
const nodes = new Map([root,dest,button,foreign].map(n=>[n.id,n]));
const context = vm.createContext({figma:{fileKey:'file',currentPage:page,getNodeByIdAsync:async id=>nodes.get(id)}});
vm.runInContext(source,context);
const call = params => context.applyPrototype(params);
const base = {fileKey:'file',pageId:'0:1',ownedRootIds:['1:1','2:1'],updates:[{nodeId:'1:2',trigger:'ON_CLICK',action:'NAVIGATE',destinationId:'2:1',transition:'DISSOLVE',duration:0.3}]};
(async()=>{
  await assert.rejects(call({...base,fileKey:'wrong'}),/identity/i);assert.equal(writes,0);
  await assert.rejects(call({...base,updates:[...base.updates,{nodeId:'9:1',trigger:'ON_CLICK',action:'BACK'}]}),/owned|page/i);assert.equal(writes,0);
  await assert.rejects(call({...base,updates:[{...base.updates[0],destinationId:'9:1'}]}),/owned|page/i);assert.equal(writes,0);
  await assert.rejects(call({...base,updates:[{...base.updates[0],duration:-1}]}),/duration/i);assert.equal(writes,0);
  await assert.rejects(call({...base,viewportHeights:[{nodeId:'1:1',height:-1}]}),/viewport/i);assert.equal(writes,0);
  await call({...base,readOnly:true,viewportHeights:[{nodeId:'1:1',height:900}]});assert.equal(writes,0);assert.equal(root.height,4432);
  const out=await call({...base,scrollFrameIds:['1:1']});assert.equal(writes,1);
  assert.equal(button.reactions[0].actions[0].destinationId,'2:1');assert.equal(button.reactions[0].actions[0].transition.duration,0.3);
  assert.equal(root.overflowDirection,'VERTICAL');assert.equal(root.clipsContent,true);assert.equal(out.nodes[0].reactions.length,1);
  await call({...base,updates:[{nodeId:'1:2',trigger:'ON_CLICK',action:'BACK'}]});assert.equal(button.reactions.length,1);assert.equal(button.reactions[0].actions[0].type,'BACK');
  await call({...base,updates:[...base.updates,{...base.updates[0],trigger:'ON_HOVER'}]});assert.equal(button.reactions.length,2);
  await call({...base,viewportHeights:[{nodeId:'1:1',height:900}]});assert.equal(root.height,900);
  const before=writes;
  await assert.rejects(call({...base,updates:[{...base.updates[0],action:'SCROLL_TO'}]}),/same frame/i);assert.equal(writes,before);
  await assert.rejects(call({...base,updates:[base.updates[0],base.updates[0]]}),/duplicate trigger/i);assert.equal(writes,before);
  const read=await call({...base,readOnly:true});assert.equal(writes,before);assert.equal(read.readOnly,true);
  console.log('PASS: identity, ownership preflight, duration, async write/readback, idempotent replacement, multiple triggers, scrolling');
})().catch(e=>{console.error(e);process.exit(1);});
